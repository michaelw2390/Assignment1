#Area and perimeter of a rectangle) Write a program that displays the area and
#perimeter of a rectangle with the width of 4.5 and height of 7.9 using the follow-
#ing formula: area = width x height

width = 4.5
Height = 7.9

area = width * Height
perimeter = 2 * (width + Height)

print(f"The area of a rectangle with a width of 4.5 and height of 7.9 is {area}")
print(f"The perimeter of a rectangle wit width of 4.5 and height of 7.9 is {perimeter}")